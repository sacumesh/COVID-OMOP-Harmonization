-- adm (administration): rows a pipeline refused, one table per layer, all with the same columns.
-- A row lands here instead of stopping the load. Each layer workflow empties its own table before it
-- runs, so a table always shows the rejects of the last run of that layer.
--   adm.sta_load_reject   file rows the staging tables refused
--   adm.ods_load_reject   staging rows that could not be converted to ODS types, or that ODS refused
--   adm.map_load_reject   rows the map tables refused
--   adm.cdm_load_reject   rows the OMOP CDM tables refused
-- Find the original line of a sta or ods reject with source_site + source_filename + source_rownum.

CREATE SCHEMA IF NOT EXISTS adm;

CREATE TABLE IF NOT EXISTS adm.sta_load_reject (
  reject_id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rejected_at        timestamp    NOT NULL DEFAULT now(),
  pipeline_name      varchar(100) NOT NULL,   -- e.g. DFT-load_ods_vitals_hospital1
  transform_name     varchar(100) NOT NULL,   -- the step that refused the row
  source_site        varchar(50),             -- hospital1, hospital2, hospital3
  source_filename    varchar(255),            -- file the row came from (empty when the row has no single source row)
  source_rownum      bigint,                  -- line number in that file
  error_count        integer,
  error_fields       text,                    -- field(s) Hop could not handle
  error_codes        text,
  error_description  text                     -- Hop's message, with the value that failed
);
CREATE INDEX IF NOT EXISTS ix_sta_load_reject_source ON adm.sta_load_reject (source_site, source_filename, source_rownum);

