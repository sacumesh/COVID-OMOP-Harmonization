-- ODS (operational data store): one table per subject, all hospitals together, EHR level (no OMOP columns).
-- Filled by WF-load_ods from staging. WF-load_ods empties these tables before every run.
-- Needs the reference tables (create_reference_tables.sql): every *_code_system column and every
-- source_site column points to them, so an unknown code system or hospital is refused (adm.ods_load_reject).
-- Every table keeps its lineage: _src_filename + _src_rownum = the line in the hospital file.

CREATE SCHEMA IF NOT EXISTS ods;

-- One row per patient per hospital
CREATE TABLE IF NOT EXISTS ods.patient (
  patient_id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_site               varchar(50)  NOT NULL,   -- hospital1, hospital2, hospital3
  patient_number            varchar(50)  NOT NULL,   -- the hospital's patient id (NHC, paciente_id, id_px)
  sex_code                  varchar(20),             -- as sent: 1 / 2 (hospital 1 only)
  sex_code_system           varchar(20),             -- H1_SEX
  birth_date                date,
  birth_time                time,                    -- empty: no hospital sends a birth time today
  death_date                date,
  death_time                time,                    -- hospital 1 only (HoraExitus)
  vital_status_code         varchar(20),             -- as sent (hospital 1 only)
  vital_status_code_system  varchar(20),             -- H1_VITAL_STATUS
  _src_filename             varchar(255),
  _src_rownum               bigint,
  _loaded_at                timestamp    NOT NULL DEFAULT now(),
  CONSTRAINT uq_patient_site_number          UNIQUE (source_site, patient_number),
  CONSTRAINT fk_patient_site                 FOREIGN KEY (source_site)              REFERENCES ods.source_site (source_site),
  CONSTRAINT fk_patient_sex_system           FOREIGN KEY (sex_code_system)          REFERENCES ods.code_system (code_system),
  CONSTRAINT fk_patient_vital_status_system  FOREIGN KEY (vital_status_code_system) REFERENCES ods.code_system (code_system)
);
-- a table created by an earlier version of this script has no birth_time yet
ALTER TABLE ods.patient ADD COLUMN IF NOT EXISTS birth_time time;

-- One row per diagnosis code given in an episode
CREATE TABLE IF NOT EXISTS ods.diagnosis (
  diagnosis_id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_site                 varchar(50)  NOT NULL,
  diagnosis_number            varchar(50),             -- the hospital's own diagnosis id (hospital 3 only)
  patient_number              varchar(50)  NOT NULL,
  episode_number              varchar(50),
  diagnosis_code              varchar(50)  NOT NULL,   -- code as the hospital sends it
  diagnosis_code_system       varchar(20)  NOT NULL,   -- from the label in the file: ICD-10-CM, ICD-9-CM, SNOMED CT
  diagnosis_text              varchar(500),            -- description as sent (hospitals 1 and 2)
  diagnosis_type_code         varchar(20),             -- P / S (hospital 1)
  diagnosis_type_code_system  varchar(20),             -- H1_DX_TYPE
  diagnosis_sequence          integer,                 -- position of the diagnosis in the episode (hospital 1)
  diagnosis_date              date         NOT NULL,
  diagnosis_time              time,
  _src_filename               varchar(255),
  _src_rownum                 bigint,
  _loaded_at                  timestamp    NOT NULL DEFAULT now(),
  CONSTRAINT fk_diagnosis_site         FOREIGN KEY (source_site)                REFERENCES ods.source_site (source_site),
  CONSTRAINT fk_diagnosis_code_system  FOREIGN KEY (diagnosis_code_system)      REFERENCES ods.code_system (code_system),
  CONSTRAINT fk_diagnosis_type_system  FOREIGN KEY (diagnosis_type_code_system) REFERENCES ods.code_system (code_system)
);
CREATE INDEX IF NOT EXISTS ix_diagnosis_patient ON ods.diagnosis (source_site, patient_number, episode_number);
CREATE INDEX IF NOT EXISTS ix_diagnosis_code    ON ods.diagnosis (diagnosis_code_system, diagnosis_code);

-- One row per drug in a prescription
CREATE TABLE IF NOT EXISTS ods.drug (
  drug_id                    bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_site                varchar(50)  NOT NULL,
  prescription_number        varchar(50)  NOT NULL,   -- the hospital's prescription id
  patient_number             varchar(50)  NOT NULL,
  episode_number             varchar(50),
  drug_code                  varchar(50)  NOT NULL,   -- code as the hospital sends it
  drug_code_system           varchar(20)  NOT NULL,   -- ATC (hospitals 1, 2), SNOMED CT (hospital 3)
  drug_local_code            varchar(50),             -- hospital 1 local drug code, e.g. G003461
  drug_local_code_system     varchar(20),             -- H1_DRUG
  drug_text                  varchar(500),            -- drug name as sent
  route_code                 varchar(50),             -- 100 / via oral / 47625008
  route_code_system          varchar(20),             -- H1_ROUTE, H2_ROUTE, SNOMED CT
  frequency_code             varchar(50),             -- C/8H / Cada 8 horas / 307469008
  frequency_code_system      varchar(20),             -- H1_FREQUENCY, H2_FREQUENCY, SNOMED CT
  start_date                 date         NOT NULL,
  start_time                 time,
  end_date                   date,
  end_time                   time,
  administration_first_date  date,                    -- hospital 1 DiaSumMin
  administration_last_date   date,                    -- hospital 1 DiaSumMax
  treatment_days             integer,                 -- hospital 1 dias_tratamiento
  _src_filename              varchar(255),
  _src_rownum                bigint,
  _loaded_at                 timestamp    NOT NULL DEFAULT now(),
  CONSTRAINT fk_drug_site               FOREIGN KEY (source_site)            REFERENCES ods.source_site (source_site),
  CONSTRAINT fk_drug_code_system        FOREIGN KEY (drug_code_system)       REFERENCES ods.code_system (code_system),
  CONSTRAINT fk_drug_local_code_system  FOREIGN KEY (drug_local_code_system) REFERENCES ods.code_system (code_system),
  CONSTRAINT fk_drug_route_system       FOREIGN KEY (route_code_system)      REFERENCES ods.code_system (code_system),
  CONSTRAINT fk_drug_frequency_system   FOREIGN KEY (frequency_code_system)  REFERENCES ods.code_system (code_system)
);
CREATE INDEX IF NOT EXISTS ix_drug_patient ON ods.drug (source_site, patient_number, episode_number);
CREATE INDEX IF NOT EXISTS ix_drug_code    ON ods.drug (drug_code_system, drug_code);

-- One row per lab test result
CREATE TABLE IF NOT EXISTS ods.lab_result (
  lab_result_id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_site                varchar(50)  NOT NULL,
  order_number               varchar(50)  NOT NULL,   -- lab order / request id
  patient_number             varchar(50)  NOT NULL,
  episode_number             varchar(50),
  test_code                  varchar(50)  NOT NULL,   -- code as the hospital sends it
  test_code_system           varchar(20)  NOT NULL,   -- H1_LAB, LOINC, H3_LAB
  test_text                  varchar(500),            -- test name as sent (hospitals 1 and 2)
  collection_date            date         NOT NULL,
  collection_time            time,
  value_text                 varchar(100),            -- result exactly as sent
  value_number               numeric,                 -- the same result as a number
  unit_code                  varchar(50),             -- unit as sent, e.g. 10^9/L
  unit_code_system           varchar(20),             -- H1_UNIT, H2_UNIT, H3_UNIT
  abnormal_flag_code         varchar(20),             -- A, B, AA, BB, Normal, Alto, Bajo
  abnormal_flag_code_system  varchar(20),             -- H1_LAB_FLAG, H3_LAB_FLAG (hospital 2 sends none)
  reference_range            varchar(100),            -- as sent, e.g. [ 4.00 - 11.00 ] (hospital 1)
  _src_filename              varchar(255),
  _src_rownum                bigint,
  _loaded_at                 timestamp    NOT NULL DEFAULT now(),
  CONSTRAINT fk_lab_result_site         FOREIGN KEY (source_site)               REFERENCES ods.source_site (source_site),
  CONSTRAINT fk_lab_result_test_system  FOREIGN KEY (test_code_system)          REFERENCES ods.code_system (code_system),
  CONSTRAINT fk_lab_result_unit_system  FOREIGN KEY (unit_code_system)          REFERENCES ods.code_system (code_system),
  CONSTRAINT fk_lab_result_flag_system  FOREIGN KEY (abnormal_flag_code_system) REFERENCES ods.code_system (code_system)
);
-- Not unique: hospital 2 sends the same LOINC code twice in one order (e.g. aPTT in seconds and as a ratio)
CREATE INDEX IF NOT EXISTS ix_lab_result_key     ON ods.lab_result (source_site, order_number, test_code);
CREATE INDEX IF NOT EXISTS ix_lab_result_patient ON ods.lab_result (source_site, patient_number, episode_number);
CREATE INDEX IF NOT EXISTS ix_lab_result_code    ON ods.lab_result (test_code_system, test_code);

-- One row per vital sign measurement
CREATE TABLE IF NOT EXISTS ods.vitals (
  vital_id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_site        varchar(50)  NOT NULL,
  vital_number       varchar(50)  NOT NULL,   -- the hospital's own id of the measurement
  patient_number     varchar(50)  NOT NULL,
  episode_number     varchar(50),
  vital_code         varchar(50)  NOT NULL,   -- code as the hospital sends it
  vital_code_system  varchar(20)  NOT NULL,   -- Nebraska Lexicon, H2_VITAL, SNOMED CT
  measurement_date   date         NOT NULL,
  measurement_time   time,
  value_text         varchar(100),            -- value exactly as sent
  value_number       numeric,                 -- the same value as a number
  _src_filename      varchar(255),
  _src_rownum        bigint,
  _loaded_at         timestamp    NOT NULL DEFAULT now(),
  CONSTRAINT uq_vitals_site_number  UNIQUE (source_site, vital_number),
  CONSTRAINT fk_vitals_site         FOREIGN KEY (source_site)       REFERENCES ods.source_site (source_site),
  CONSTRAINT fk_vitals_code_system  FOREIGN KEY (vital_code_system) REFERENCES ods.code_system (code_system)
);
CREATE INDEX IF NOT EXISTS ix_vitals_patient ON ods.vitals (source_site, patient_number, episode_number);
CREATE INDEX IF NOT EXISTS ix_vitals_code    ON ods.vitals (vital_code_system, vital_code);
