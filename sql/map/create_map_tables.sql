-- Map layer between ODS (EHR level) and the OMOP CDM. Filled by WF-load_map.
-- Standard OMOP procedure for codes:
--   * code of a standard vocabulary (ICD10CM, SNOMED, LOINC, ATC, ...) -> its 'Maps to' standard concept(s)
--   * local code -> cdm.source_to_concept_map when a reviewed mapping exists, otherwise concept_id 0
--   * every CDM row keeps the code in *_source_value, so nothing is lost and it can be remapped later
--   * codes that end at concept_id 0 are listed in map.unmapped_codes (the report)
-- The hand-kept tables of this layer (code_system_vocabulary, unit_rule) are in create_reference_tables.sql.

CREATE SCHEMA IF NOT EXISTS map;

-- Stable ids, kept between runs (never emptied): a patient or episode keeps its id once given.
CREATE TABLE IF NOT EXISTS map.person_map (
  person_id       integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_site     varchar(50) NOT NULL,
  patient_number  varchar(50) NOT NULL,
  CONSTRAINT uq_person_map UNIQUE (source_site, patient_number)
);

CREATE TABLE IF NOT EXISTS map.visit_map (
  visit_occurrence_id  integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_site          varchar(50) NOT NULL,
  patient_number       varchar(50) NOT NULL,
  episode_number       varchar(50) NOT NULL,
  CONSTRAINT uq_visit_map UNIQUE (source_site, patient_number, episode_number)
);

-- Rebuilt on every run (emptied by truncate_map_tables.sql):

-- The codes the CDM needs, with how often they are used
CREATE TABLE IF NOT EXISTS map.code_usage (
  ods_column    varchar(60)  NOT NULL,   -- e.g. diagnosis.diagnosis_code
  code_system   varchar(20)  NOT NULL,
  source_code   varchar(50)  NOT NULL,
  source_name   varchar(500),            -- one description of the code as sent, when the hospital sends one
  record_count  integer      NOT NULL,
  person_count  integer      NOT NULL,
  PRIMARY KEY (ods_column, code_system, source_code)
);

-- Code -> standard concept(s), one row per target (a code can map to more than one concept).
-- Unmapped codes are here too, with target_concept_id = 0, so every code has at least one row.
CREATE TABLE IF NOT EXISTS map.code_map (
  code_system              varchar(20)  NOT NULL,
  source_code              varchar(50)  NOT NULL,
  source_concept_id        integer      NOT NULL,   -- the code's own concept, 0 when it has none
  target_concept_id        integer      NOT NULL,   -- standard concept, 0 = no mapping
  target_domain_id         varchar(20),             -- decides the CDM table (Condition, Observation, ...)
  target_value_concept_id  integer,                 -- from 'Maps to value'
  mapping_source           varchar(30)  NOT NULL,   -- vocabulary | source_to_concept_map | unmapped
  unmapped_reason          varchar(100)
);
CREATE INDEX IF NOT EXISTS ix_code_map_code ON map.code_map (code_system, source_code);

-- Lab results whose code cannot tell which result it is: the same test code more than once in one order
-- (hospital 2 sends, for example, aPTT in seconds and as a ratio under one LOINC code). Their
-- measurement_concept_id becomes 0 (used by DFT-load_cdm_measurement_lab).
CREATE TABLE IF NOT EXISTS map.lab_ambiguous_code (
  source_site      varchar(50) NOT NULL,
  order_number     varchar(50) NOT NULL,
  test_code        varchar(50) NOT NULL,
  result_count     integer     NOT NULL,
  accepted_domain  varchar(20) NOT NULL DEFAULT 'none (ambiguous)',   -- no concept domain is accepted
  PRIMARY KEY (source_site, order_number, test_code)
);

-- Episodes have no admission or discharge dates in the source: a visit runs from the first to the last
-- event date of its episode (diagnoses, drug starts, lab collections, vital signs).
CREATE OR REPLACE VIEW map.visit_source AS
SELECT v.visit_occurrence_id, v.source_site, v.patient_number, v.episode_number,
       min(e.event_date) AS visit_start_date,
       max(e.event_date) AS visit_end_date
FROM map.visit_map v
JOIN (SELECT source_site, patient_number, episode_number, diagnosis_date AS event_date FROM ods.diagnosis
      UNION ALL SELECT source_site, patient_number, episode_number, start_date FROM ods.drug
      UNION ALL SELECT source_site, patient_number, episode_number, collection_date FROM ods.lab_result
      UNION ALL SELECT source_site, patient_number, episode_number, measurement_date FROM ods.vitals) e
  ON e.source_site = v.source_site AND e.patient_number = v.patient_number AND e.episode_number = v.episode_number
GROUP BY v.visit_occurrence_id, v.source_site, v.patient_number, v.episode_number;

-- The report: every code that ends at concept_id 0, with how many records it affects.
-- Columns sourceCode / sourceName / sourceFrequency are the ones Usagi reads.
DROP VIEW IF EXISTS map.unmapped_codes;
CREATE VIEW map.unmapped_codes AS
SELECT u.ods_column,
       u.code_system,
       coalesce(r.rule, m.unmapped_reason)::varchar(200) AS unmapped_reason,
       u.source_code   AS "sourceCode",
       u.source_name   AS "sourceName",
       u.record_count  AS "sourceFrequency",
       u.person_count
FROM map.code_usage u
JOIN (SELECT DISTINCT code_system, source_code, unmapped_reason
      FROM map.code_map WHERE mapping_source = 'unmapped') m
  ON m.code_system = u.code_system AND m.source_code = u.source_code
LEFT JOIN map.unit_rule r
  ON u.ods_column = 'lab_result.unit_code' AND r.unit_as_sent = u.source_code AND r.tier = 3;

-- Coverage per coded column
DROP VIEW IF EXISTS map.mapping_coverage;
CREATE VIEW map.mapping_coverage AS
SELECT u.ods_column,
       u.code_system,
       count(*)                                                            AS codes,
       count(*) FILTER (WHERE mapped.code_system IS NOT NULL)              AS codes_mapped,
       sum(u.record_count)                                                 AS records,
       sum(u.record_count) FILTER (WHERE mapped.code_system IS NOT NULL)   AS records_mapped,
       round(100.0 * coalesce(sum(u.record_count) FILTER (WHERE mapped.code_system IS NOT NULL), 0)
             / sum(u.record_count), 1)                                     AS pct_records_mapped
FROM map.code_usage u
LEFT JOIN (SELECT DISTINCT code_system, source_code FROM map.code_map WHERE target_concept_id <> 0) mapped
  ON mapped.code_system = u.code_system AND mapped.source_code = u.source_code
GROUP BY u.ods_column, u.code_system;
